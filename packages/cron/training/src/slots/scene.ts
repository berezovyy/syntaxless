function defaultPrep(text: string): string {
  if (
    /\b(loft|room|shop|house|hall|office|vault|cellar|lab|studio|annex|hut|bay|gallery|barn|shack|crib|shed|attic)\b/.test(
      text,
    )
  ) {
    return "in";
  }

  if (/\b(deck|floor|yard|platform|catwalk|dock|gate|walk|aisle)\b/.test(text)) return "on";
  if (/\b(tank|kettle|barge|post|buoy)\b/.test(text)) return "by";

  return "at";
}

