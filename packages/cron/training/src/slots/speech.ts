/**
 * Speech frames: how the speaker treats the hole (ask / mention / take back).
 * Migrated POSITIVE_CARRIERS live here as request prefixes.
 */
import type { SpeechAct } from "../../../src/model/speech-acts";
import type { SpeechFrame } from "./types";

function frame(
  act: SpeechAct,
  id: string,
  prefix?: string,
  suffix?: string,
  quoted?: boolean,
): SpeechFrame {
  return {
    id: `${act}-${id}`,
    act,
    ...(prefix !== undefined ? { prefix } : {}),
    ...(suffix !== undefined ? { suffix } : {}),
    ...(quoted === true ? { quoted: true } : {}),
  };
}

